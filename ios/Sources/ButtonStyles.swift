import SwiftUI

// MARK: - 全 App 的按钮 / 开关语言（用户 2026-11-15 定）

/// **「蓝色」只属于控件本体，文字一律主色。**
///
/// 用户 2026-11-02 就说过一次「蓝色配色换成黑」，指的是按钮上的字；
/// 2026-11-15 又说了一次，这次给了图：他要的「按钮变蓝」是**开关**（iOS 那个
/// 蓝色胶囊），不是把每个文字按钮都刷成蓝字。原话：
/// 「你把所有按钮都改成蓝色，错了，而是改这种按钮……要有大局，看整个软件，
/// 一样的按钮要统一样式」。
///
/// 所以定成四类，各自只有一种写法：
///
/// | 类别 | 例子 | 颜色 |
/// | --- | --- | --- |
/// | ① 开关 `Toggle` | 隐藏网络、阻止入网、启用中继 | **系统蓝**，`blueSwitch()` |
/// | ② 导航栏按钮 | 保存 / 取消 / 完成 / 关闭 | **主色黑字**，`navBarTint()` |
/// | ③ 行内文字按钮 | 切换、切到以太网、扫描周边 Wi-Fi | **主色黑字**（`primaryButtons()`） |
/// | ④ 主操作按钮 | 连接并保存这种整宽实心 | **蓝底白字**，`GlassProminentButtonStyle` |
/// | ⑤ 卡片里的块状按钮 | 重新检测、编辑订阅 | **蓝字 + 14% 蓝底**（v1.28 起的设计语言，不动） |
///
/// 蓝只有这四处：开关、主操作、卡片块状按钮、进度条 / 滑条。**文字按钮不蓝。**
///
/// 反面教材（v2.9.0）：为了修「网络页按钮全是黑的」，给网络那条线**整页**
/// `.tint(.blue)`，导航栏、行内按钮、开关一起变蓝——用户当场退回。
/// 正确的做法是**只给 `Toggle` 上蓝**，其余交给全 App 的主色。
extension View {
    /// 开关统一的蓝色（① 类）。
    ///
    /// 只加在 `Toggle` 自己身上，别加在 `Form` / 整页上——那会把同一容器里的
    /// 所有 `Button` 文字一起染蓝，就是 v2.9.0 犯的错。
    func blueSwitch() -> some View {
        tint(.blue)
    }

    /// 页面内容区的「按钮文字＝主色」（②③ 类）。
    ///
    /// 挂在 `Form` / `ScrollView` 内容上，等价于「这个容器里的按钮别再发蓝」。
    /// `Toggle` 不受影响——它们的蓝由各自的 `blueSwitch()` 保着。
    func primaryButtons() -> some View {
        tint(.primary)
    }
}
