///
/// 来源：路由器网页版 `/www/fonts/iconfont.e491c426.ttf` 这个字体——GL 自家那套图标，
/// 和官方 App「设备类型」弹窗上的图形是同一套。类名与码点的对应写在网页主包的 CSS 里
/// （`.icon-phone:before{content:"\\e62f"}`），类型清单在 `clientTypes` 数组里。
///
/// 生成方式：`tmp/font2swift.py` 把 TTF 的二次曲线原样翻译成 SwiftUI `Path`，
/// 只做「em 1024 → 24 网格」的等比缩放与 y 轴翻转，**控制点一个没改**（和 v3.0.6
/// 从 Lucide 翻译那批一样的做法）。字形本身是把约 2px 的描边展开成的实心轮廓，
/// 所以画的时候必须 `fill`（非零环绕）：用 `stroke` 描它，每根线两侧会再多出一圈。
///
/// 「默认」（`.auto`）没有官方字形——网页端根本没有这一项，官方 App 那格是
/// 「显示器 + 手机」的定制图，留在 `DeviceGlyph` 里手绘。
enum OfficialGlyph {
    static func draw(_ kind: ClientClass, into p: inout Path, scale k: CGFloat) {
        switch kind {
        case .phone: phone(&p, k)
        case .pad: pad(&p, k)
        case .laptop: laptop(&p, k)
        case .computer: computer(&p, k)
        case .television: television(&p, k)
        case .camera: camera(&p, k)
        case .sound: sound(&p, k)
        case .printer: printer(&p, k)
        case .watch: watch(&p, k)
        case .games: games(&p, k)
        case .smartAppliances: smartAppliances(&p, k)
        case .gateway: gateway(&p, k)
        case .nas: nas(&p, k)
        case .server: server(&p, k)
        case .networkSwitch: networkSwitch(&p, k)
        case .auto: break          // 手绘，见 DeviceGlyph.defaultMark
        }
    }

